export type RentalDocumentKind = "NFSE" | "INVOICE" | "RENTAL_RECEIPT" | "OTHER";
export type RentalStatus = "SCHEDULED" | "ACTIVE" | "RETURNED";
export type RentalProject = { id: string; code: string; name: string; active: boolean };
export type RentalSupplier = { id: string; name: string };
export type RentalFileMetadata = { id: string; fileName: string; mediaType: string; sizeBytes: number };
export type RentalChargeRow = {
  id: string;
  rentalId: string;
  documentKind: RentalDocumentKind;
  documentNumber: string;
  issuedAt: string;
  dueAt: string;
  amount: string;
  documentUrl: string;
  notes: string;
  payable: { id: string; status: "OPEN" | "PAID" | "CANCELLED"; paidAt: string | null; financialTitleId: string | null } | null;
  files: RentalFileMetadata[];
};
export type EquipmentRentalRow = {
  id: string;
  number: string;
  equipmentName: string;
  equipmentIdentifier: string;
  quantity: number;
  startsAt: string;
  expectedReturnAt: string | null;
  returnedAt: string | null;
  notes: string;
  revision: number;
  project: RentalProject;
  supplier: RentalSupplier;
  status: RentalStatus;
  chargeCount: number;
  totalCharged: string;
  totalPaid: string;
  totalOutstanding: string;
};
export type EquipmentRentalDetail = EquipmentRentalRow & { charges: RentalChargeRow[] };
export type RentalOptions = { projects: RentalProject[]; suppliers: RentalSupplier[] };
